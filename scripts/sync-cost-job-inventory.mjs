import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const SOURCE_ORIGIN = "https://www.myjobquote.co.uk";
const OUTPUT_PATH = resolve("src/data/cost-job-inventory.ts");

const CATEGORIES = [
  ["bathrooms", "bathrooms"],
  ["carpentry-windows-doors", "carpentry-windows-and-doors"],
  ["conversions", "conversions"],
  ["kitchens", "kitchens"],
  ["electrical-lighting", "electricals-and-lighting"],
  ["flooring-carpets", "flooring-and-carpets"],
  ["decorating-plastering", "painting-decorating-and-plastering"],
  ["plumbing-heating", "plumbing-and-heating"],
  ["drainage", "drainage"],
  ["driveways-paving", "driveways-and-paving"],
  ["extensions", "extensions"],
  ["gardens-fences", "gardening-sheds-fences-and-gates"],
  ["gutters-roofline", "guttering-fascias-and-soffits"],
  ["energy-saving", "energy-saving"],
  ["external-finishes", "painting-and-rendering"],
  ["roofs-chimneys", "roofs-and-chimneys"],
];

function decodeEntities(value) {
  return value
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;|&apos;/g, "’")
    .replace(/&pound;/g, "£")
    .replace(/&ndash;/g, "–")
    .replace(/&mdash;/g, "—")
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/\s+/g, " ")
    .trim();
}

function titleFromSlug(slug) {
  const lowerWords = new Set(["a", "an", "and", "at", "for", "in", "of", "on", "or", "the", "to", "with"]);
  return slug
    .split("-")
    .map((word, index) => index && lowerWords.has(word) ? word : `${word.charAt(0).toUpperCase()}${word.slice(1)}`)
    .join(" ");
}

async function fetchText(path) {
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    const response = await fetch(`${SOURCE_ORIGIN}${path}`, {
      headers: { "user-agent": "Mozilla/5.0 (compatible; BuilderFind inventory audit/1.0)" },
    });
    if (response.ok) return response.text();
    if (attempt === 4 || ![403, 429, 500, 502, 503, 504].includes(response.status)) {
      throw new Error(`${path} returned ${response.status}`);
    }
    await new Promise((resolveDelay) => setTimeout(resolveDelay, attempt * 750));
  }
  throw new Error(`${path} could not be fetched`);
}

function parseCategoryJobs(html) {
  return [...html.matchAll(/<a class="single" href="\/costs\/([^"]+)">[\s\S]*?<div class="category-title">([\s\S]*?)<\/div>/g)]
    .map((match) => ({ slug: match[1], title: decodeEntities(match[2]) }));
}

async function mapWithConcurrency(items, concurrency, callback) {
  const results = new Array(items.length);
  let nextIndex = 0;
  async function worker() {
    while (nextIndex < items.length) {
      const index = nextIndex++;
      results[index] = await callback(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, worker));
  return results;
}

const sitemap = await fetchText("/sitemap.guides.xml");
const allSlugs = [...sitemap.matchAll(/<loc>https:\/\/www\.myjobquote\.co\.uk\/costs\/([^<]+)<\/loc>/g)]
  .map((match) => match[1]);

const jobs = new Map(allSlugs.map((slug) => [slug, {
  slug,
  title: titleFromSlug(slug),
  categorySlugs: [],
}]));

for (const [builderFindSlug, sourceSlug] of CATEGORIES) {
  const html = await fetchText(`/costs/${sourceSlug}`);
  for (const article of parseCategoryJobs(html)) {
    const job = jobs.get(article.slug) ?? { slug: article.slug, title: article.title, categorySlugs: [] };
    job.title = article.title;
    if (!job.categorySlugs.includes(builderFindSlug)) job.categorySlugs.push(builderFindSlug);
    jobs.set(article.slug, job);
  }
}

const unmapped = [...jobs.values()].filter((job) => job.categorySlugs.length === 0);
await mapWithConcurrency(unmapped, 6, async (job) => {
  try {
    const html = await fetchText(`/costs/${job.slug}`);
    const title = html.match(/<title>([\s\S]*?)<\/title>/i)?.[1];
    if (title) job.title = decodeEntities(title).replace(/\s*\|\s*.*$/, "").trim();
  } catch {
    // A readable slug title is retained if the source page is temporarily unavailable.
  }
});

const inventory = [...jobs.values()].sort((left, right) => left.title.localeCompare(right.title, "en-GB"));
const categoryPlacements = inventory.reduce((total, job) => total + job.categorySlugs.length, 0);

const output = `// Generated by scripts/sync-cost-job-inventory.mjs on 2026-08-15.\n// The inventory mirrors public job titles and taxonomy only; no third-party article prose is stored.\n\nexport type CostJobListing = {\n  slug: string;\n  title: string;\n  categorySlugs: readonly string[];\n};\n\nexport const COST_JOB_LISTINGS: readonly CostJobListing[] = ${JSON.stringify(inventory, null, 2)};\n\nexport const COST_JOB_BY_SLUG = new Map(COST_JOB_LISTINGS.map((job) => [job.slug, job]));\n`;

await mkdir(dirname(OUTPUT_PATH), { recursive: true });
await writeFile(OUTPUT_PATH, output);
console.log(JSON.stringify({ jobs: inventory.length, categoryPlacements, unmapped: unmapped.length }));
